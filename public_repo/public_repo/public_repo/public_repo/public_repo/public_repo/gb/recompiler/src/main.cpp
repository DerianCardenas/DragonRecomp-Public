#include <cstdio>
#include <cstring>
#include <exception>
#include <filesystem>
#include <string>
#include <vector>

#include "dragon/config.h"
#include "dragon/file_io.h"
#include "dragon/log.h"
#include "gb/cartridge.h"
#include "gbrecomp/disassembler.h"
#include "gbrecomp/emitter.h"

namespace {

void print_usage() {
    std::printf(
        "usage: gbrecomp <game.toml> [--rom <path>] [--out <dir>] [--single-file]\n"
        "       gbrecomp --version\n");
}

}  // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        print_usage();
        return 1;
    }

    for (int i = 1; i < argc; ++i) {
        if (std::strcmp(argv[i], "--version") == 0) {
            std::printf("gbrecomp 0.1.0\n");
            return 0;
        }
        if (std::strcmp(argv[i], "--help") == 0 || std::strcmp(argv[i], "-h") == 0) {
            print_usage();
            return 0;
        }
    }

    std::filesystem::path config_path;
    std::filesystem::path rom_override;
    std::filesystem::path out_override;
    bool single_file = false;

    for (int i = 1; i < argc; ++i) {
        const std::string arg = argv[i];
        if (arg == "--single-file") {
            single_file = true;
        } else if (arg == "--rom" && i + 1 < argc) {
            rom_override = argv[++i];
        } else if (arg == "--out" && i + 1 < argc) {
            out_override = argv[++i];
        } else if (!arg.empty() && arg[0] != '-' && config_path.empty()) {
            config_path = arg;
        } else {
            std::fprintf(stderr, "error: unknown argument '%s'\n", arg.c_str());
            return 1;
        }
    }

    if (config_path.empty()) {
        std::fprintf(stderr, "error: no config file specified\n");
        return 1;
    }

    try {
        dragon::GameConfig config = dragon::load_game_config(config_path);
        if (!rom_override.empty()) {
            config.rom_path = rom_override;
        }
        if (!out_override.empty()) {
            config.output_dir = out_override;
        }

        if (config.output_dir.empty()) {
            config.output_dir = config_path.parent_path() / "generated";
        }

        dragon::gb::Cartridge cart = dragon::gb::load_gb_rom(config.rom_path, config.sha1);
        std::printf("Loaded GB ROM: %s (%u KB)\n", cart.title.c_str(), cart.rom_size / 1024U);

        dragon::gbrecomp::ProgramCFG cfg = dragon::gbrecomp::disassemble_game_boy(cart.rom, config);

        size_t total_funcs = 0;
        for (const auto& [bank, bank_cfg] : cfg.banks) {
            total_funcs += bank_cfg.functions.size();
        }
        std::printf("Disassembled %zu functions across %zu banks.\n", total_funcs,
                    cfg.banks.size());

        dragon::gbrecomp::EmitOptions opts;
        if (single_file) {
            opts.split_every = 100'000;
        }

        auto paths = dragon::gbrecomp::write_generated_output(cfg, config, config.output_dir, opts);
        std::printf("Emitted %zu files to '%s'.\n", paths.size(),
                    config.output_dir.string().c_str());

        // Per-game report (spec 003, §3.5) — see nesrecomp's main.cpp for rationale.
        char report_buf[512];
        std::snprintf(report_buf, sizeof(report_buf),
                      "# Generated by gbrecomp. Do not edit; reflects the last recompilation.\n"
                      "[game]\n"
                      "name = \"%s\"\n"
                      "sha1 = \"%s\"\n"
                      "\n"
                      "[recompiler]\n"
                      "interpreter_only = %s\n"
                      "functions = %zu\n"
                      "banks = %zu\n",
                      config.name.c_str(), cart.sha1.c_str(),
                      config.interpreter_only ? "true" : "false", total_funcs, cfg.banks.size());
        dragon::write_text_file(config.output_dir / "report.toml", report_buf);

        return 0;
    } catch (const std::exception& ex) {
        std::fprintf(stderr, "error: %s\n", ex.what());
        return 1;
    }
}
