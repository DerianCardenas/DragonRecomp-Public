#include <cstdio>
#include <cstring>
#include <exception>
#include <filesystem>
#include <string>

#include "dragon/config.h"
#include "dragon/file_io.h"
#include "snes/cartridge.h"
#include "snesrecomp/disassembler.h"
#include "snesrecomp/emitter.h"

namespace {

void print_usage() {
    std::printf(
        "usage: snesrecomp <game.toml> [--rom <path>] [--out <dir>] [--no-flag-opt] "
        "[--single-file]\n"
        "       snesrecomp --version\n");
}

const char* map_mode_str(dragon::snes::MapMode m) noexcept {
    switch (m) {
        case dragon::snes::MapMode::LoROM:
            return "LoROM";
        case dragon::snes::MapMode::HiROM:
            return "HiROM";
        case dragon::snes::MapMode::ExHiROM:
            return "ExHiROM";
    }
    return "Unknown";
}

}  // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        print_usage();
        return 1;
    }

    for (int i = 1; i < argc; ++i) {
        if (std::strcmp(argv[i], "--version") == 0) {
            std::printf("snesrecomp 0.1.0\n");
            return 0;
        }
        if (std::strcmp(argv[i], "--help") == 0 || std::strcmp(argv[i], "-h") == 0) {
            print_usage();
            return 0;
        }
    }

    std::filesystem::path config_path;
    std::filesystem::path rom_override;
    std::filesystem::path out_override;
    bool enable_flag_opt = true;
    bool single_file = false;

    for (int i = 1; i < argc; ++i) {
        const std::string arg = argv[i];
        if (arg == "--no-flag-opt") {
            enable_flag_opt = false;
        } else if (arg == "--single-file") {
            single_file = true;
        } else if (arg == "--rom" && i + 1 < argc) {
            rom_override = argv[++i];
        } else if (arg == "--out" && i + 1 < argc) {
            out_override = argv[++i];
        } else if (!arg.empty() && arg[0] != '-' && config_path.empty()) {
            config_path = arg;
        } else {
            std::fprintf(stderr, "snesrecomp: unknown or incomplete option '%s'\n", arg.c_str());
            print_usage();
            return 1;
        }
    }

    if (config_path.empty()) {
        std::fprintf(stderr, "snesrecomp: missing <game.toml> path\n");
        print_usage();
        return 1;
    }

    try {
        dragon::GameConfig config = dragon::load_game_config(config_path);
        if (!rom_override.empty()) {
            config.rom_path = rom_override;
        }
        if (!out_override.empty()) {
            config.output_dir = out_override;
        }

        const dragon::snes::Cartridge cart =
            dragon::snes::load_snes_rom(config.rom_path, config.sha1, config.map);
        const dragon::snesrecomp::ProgramCFG cfg =
            dragon::snesrecomp::analyze_snes_rom(cart, config);

        dragon::snesrecomp::EmitOptions emit_opts;
        emit_opts.enable_flag_opt = enable_flag_opt;
        emit_opts.split_every = single_file ? 1000000U : config.split_every;

        const auto written_files =
            dragon::snesrecomp::write_generated_output(cfg, config, config.output_dir, emit_opts);

        std::printf("snesrecomp: '%s' (%s)\n", config.name.c_str(),
                    config.rom_path.string().c_str());
        std::printf("  Internal title:     '%s'\n", cart.title.c_str());
        std::printf("  SHA-1:              %s\n", cart.sha1.c_str());
        std::printf("  ROM size:           %zu bytes (%s, mode=$%02X%s)\n", cart.rom.size(),
                    map_mode_str(cart.map_mode), cart.map_mode_byte,
                    cart.has_fastrom ? ", FastROM" : "");
        std::printf("  Vectors (Emu):      RESET=$%04X NMI=$%04X IRQ=$%04X\n",
                    cart.emu_vectors.reset, cart.emu_vectors.nmi, cart.emu_vectors.irq);
        std::printf("  Vectors (Native):   NMI=$%04X IRQ=$%04X BRK=$%04X COP=$%04X\n",
                    cart.native_vectors.nmi, cart.native_vectors.irq, cart.native_vectors.brk,
                    cart.native_vectors.cop);
        std::printf("  Functions:          %zu\n", cfg.functions.size());
        std::printf("  Basic blocks:       %zu\n", cfg.total_blocks);
        std::printf("  Instructions:       %zu\n", cfg.total_instructions);
        std::printf("  Output directory:   %s (%zu files written)\n",
                    config.output_dir.string().c_str(), written_files.size());

        // Per-game report (spec 003, §3.5) — see nesrecomp's main.cpp for rationale.
        char report_buf[1024];
        std::snprintf(report_buf, sizeof(report_buf),
                      "# Generated by snesrecomp. Do not edit; reflects the last recompilation.\n"
                      "[game]\n"
                      "name = \"%s\"\n"
                      "sha1 = \"%s\"\n"
                      "map_mode = \"%s\"\n"
                      "\n"
                      "[recompiler]\n"
                      "interpreter_only = %s\n"
                      "functions = %zu\n"
                      "basic_blocks = %zu\n"
                      "instructions = %zu\n",
                      config.name.c_str(), cart.sha1.c_str(), map_mode_str(cart.map_mode),
                      config.interpreter_only ? "true" : "false", cfg.functions.size(),
                      cfg.total_blocks, cfg.total_instructions);
        dragon::write_text_file(config.output_dir / "report.toml", report_buf);

        return 0;
    } catch (const std::exception& ex) {
        std::fprintf(stderr, "snesrecomp error: %s\n", ex.what());
        return 1;
    }
}
