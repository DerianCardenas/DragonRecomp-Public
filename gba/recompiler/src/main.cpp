#include <cstdio>
#include <cstring>
#include <exception>
#include <filesystem>
#include <string>
#include <vector>

#include "dragon/config.h"
#include "dragon/file_io.h"
#include "gba/cartridge.h"
#include "gbarecomp/disassembler.h"
#include "gbarecomp/emitter.h"

namespace {

void print_usage() {
    std::printf(
        "usage: gbarecomp <game.toml> [--rom <path>] [--out <dir>] [--single-file]\n"
        "       gbarecomp --version\n");
}

}  // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        print_usage();
        return 1;
    }

    for (int i = 1; i < argc; ++i) {
        if (std::strcmp(argv[i], "--version") == 0) {
            std::printf("gbarecomp 0.1.0\n");
            return 0;
        }
        if (std::strcmp(argv[i], "--help") == 0 || std::strcmp(argv[i], "-h") == 0) {
            print_usage();
            return 0;
        }
    }

    std::filesystem::path config_path;
    std::filesystem::path rom_override;
    std::filesystem::path out_override;
    bool single_file = false;

    for (int i = 1; i < argc; ++i) {
        const std::string arg = argv[i];
        if (arg == "--single-file") {
            single_file = true;
        } else if (arg == "--rom" && i + 1 < argc) {
            rom_override = argv[++i];
        } else if (arg == "--out" && i + 1 < argc) {
            out_override = argv[++i];
        } else if (!arg.empty() && arg[0] != '-' && config_path.empty()) {
            config_path = arg;
        } else {
            std::fprintf(stderr, "error: unknown argument '%s'\n", arg.c_str());
            return 1;
        }
    }

    if (config_path.empty()) {
        std::fprintf(stderr, "error: no config file specified\n");
        return 1;
    }

    try {
        dragon::GameConfig config = dragon::load_game_config(config_path);
        if (!rom_override.empty()) {
            config.rom_path = rom_override;
        }
        if (!out_override.empty()) {
            config.output_dir = out_override;
        }

        if (config.output_dir.empty()) {
            config.output_dir = config_path.parent_path() / "generated";
        }

        dragon::gba::Cartridge cart = dragon::gba::load_gba_rom(config.rom_path, config.sha1);
        dragon::gbarecomp::ProgramCFG cfg = dragon::gbarecomp::disassemble_gba(cart.rom, config);

        size_t total_instructions = 0;
        for (const auto& [key, func] : cfg.functions) {
            (void)key;
            total_instructions += func.instructions.size();
        }

        dragon::gbarecomp::EmitOptions opts;
        opts.split_every = single_file ? 500U : config.split_every;

        auto paths =
            dragon::gbarecomp::write_generated_output(cfg, config, config.output_dir, opts);

        std::printf("gbarecomp: '%s' (%s)\n", config.name.c_str(),
                    config.rom_path.string().c_str());
        std::printf("  Internal title:     '%s' (%s)\n", cart.title.c_str(),
                    cart.game_code.c_str());
        std::printf("  SHA-1:              %s\n", cart.sha1.c_str());
        std::printf("  ROM size:           %u bytes\n", cart.rom_size);
        std::printf("  Save type:          %s\n", dragon::gba::save_type_to_string(cart.save_type));
        std::printf("  Functions:          %zu\n", cfg.functions.size());
        std::printf("  Basic blocks:       %zu\n", cfg.blocks.size());
        std::printf("  Instructions:       %zu\n", total_instructions);
        std::printf("  Output directory:   %s (%zu files written)\n",
                    config.output_dir.string().c_str(), paths.size());

        // Per-game report (spec 003, §3.5) — see nesrecomp's main.cpp for rationale.
        char report_buf[512];
        std::snprintf(report_buf, sizeof(report_buf),
                      "# Generated by gbarecomp. Do not edit; reflects the last recompilation.\n"
                      "[game]\n"
                      "name = \"%s\"\n"
                      "sha1 = \"%s\"\n"
                      "\n"
                      "[recompiler]\n"
                      "interpreter_only = %s\n"
                      "functions = %zu\n"
                      "basic_blocks = %zu\n"
                      "instructions = %zu\n",
                      config.name.c_str(), cart.sha1.c_str(),
                      config.interpreter_only ? "true" : "false", cfg.functions.size(),
                      cfg.blocks.size(), total_instructions);
        dragon::write_text_file(config.output_dir / "report.toml", report_buf);

        return 0;
    } catch (const std::exception& ex) {
        std::fprintf(stderr, "error: %s\n", ex.what());
        return 1;
    }
}
